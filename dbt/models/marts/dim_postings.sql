-- One row per posting (per source). Use is_canonical = true to count unique jobs.
select
    c.posting_id,
    c.source_id,
    s.display_name as source_name,
    c.source_job_id,
    c.scope_key,
    c.url,
    c.title_raw,
    c.title_clean,
    c.company_raw,
    c.company_clean,
    c.location_raw,
    c.location_cities,
    coalesce((select min(x) from unnest(c.location_cities) as x), 'Unspecified') as primary_city,
    c.location_country,
    c.working_arrangement,
    c.arrangement_evidence,
    c.salary_min,
    c.salary_max,
    c.salary_currency,
    c.salary_period,
    c.salary_period_inferred,
    c.salary_source,
    c.salary_raw,
    c.salary_min is not null or c.salary_max is not null as has_salary,
    c.posted_date,
    coalesce(c.role_category, 'unknown') as role_category,
    c.role_evidence,
    coalesce(c.seniority, 'unknown') as seniority,
    c.seniority_source,
    c.seniority_evidence,
    coalesce(c.seniority, 'unknown') in ('intern', 'entry') as is_entry_level,
    coalesce(c.role_category, 'unknown')
        in ('data_analyst', 'data_engineer', 'analytics_engineer') as is_target_role,
    c.first_seen_at,
    c.last_seen_at,
    c.n_observations,
    c.n_versions,
    a.is_active,
    a.n_successful_batches_missed,
    a.scope_retired,
    a.inactive_since,
    k.cluster_id,
    k.cluster_size,
    k.cluster_n_sources,
    k.is_canonical,
    c.version_id as current_version_id,
    c.parser_version
from {{ ref('int_posting_current') }} c
join {{ ref('int_posting_activity') }} a using (posting_id)
join {{ ref('int_posting_clusters') }} k using (posting_id)
join {{ source('ops', 'source') }} s on s.source_id = c.source_id
